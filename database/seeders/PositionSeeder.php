            }

            $childKey = $this->key($sede, $department, $position);
            $supervisorKey = $this->key($supervisorSede, $supervisorDepartment, $supervisorPosition);

            if (! array_key_exists($childKey, $map) || ! array_key_exists($supervisorKey, $map)) {
                throw new RuntimeException("La relación jerárquica referencia un puesto inexistente: {$line}");
            }

            if ($childKey === $supervisorKey) {
                throw new RuntimeException("La relación jerárquica se autorreferencia: {$line}");
            }

            if (! $this->hasExplicitAuthority($supervisorPosition)) {
                throw new RuntimeException("El supervisor no tiene autoridad explícita: {$line}");
            }

            $map[$childKey] = $supervisorKey;
        }

        $this->assertAcyclic($map);

        return $map;
    }

    private function hasExplicitAuthority(string $position): bool
    {
        $upper = mb_strtoupper($position);

        foreach (['CONSEJERO', 'DIRECTOR', 'DIRECTORA', 'GERENTE', 'COORDINADOR', 'COORD ', 'SUBCOORD', 'SUPERVISOR', 'JEFE', 'TECNICO LIDER'] as $authority) {
            if (str_contains($upper, $authority)) {
                return true;
            }
        }

        return false;
    }

    /** @param array<string, string|null> $map */
    private function assertAcyclic(array $map): void
    {
        foreach (array_keys($map) as $origin) {
            $visited = [];
            $current = $origin;

            while (($map[$current] ?? null) !== null) {
                if (isset($visited[$current])) {
                    throw new RuntimeException("El mapa jerárquico contiene un ciclo desde: {$origin}");
                }

                $visited[$current] = true;
                $current = $map[$current];
            }
        }
    }

    private function key(string $sede, string $department, string $position): string
    {
        return implode("\x1F", [$sede, $department, $position]);
    }
}
