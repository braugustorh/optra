    public function run(): void
    {
        DB::transaction(function (): void {
            $sedeIds = $this->resolveSedeIds();
            $rows = $this->rows();
            $positionIds = [];
            $supervisors = $this->supervisorMap($rows);

            foreach ($rows as $row) {
                [$sedeName, $departmentName, $positionName] = $row;
                $sedeId = $sedeIds[$sedeName];

                DB::table('departments')->updateOrInsert(
                    ['sede_id' => $sedeId, 'name' => $departmentName],
                    ['status' => true, 'updated_at' => now()],
                );

                $departmentId = (int) DB::table('departments')
                    ->where('sede_id', $sedeId)->where('name', $departmentName)->value('id');
                $order = $this->hierarchyOrder($positionName);

                DB::table('positions')->updateOrInsert(
                    ['department_id' => $departmentId, 'name' => $positionName],
                    [
                        'evaluation_grades' => self::EVALUATION_GRADES,
                        'description' => null,
                        'order' => $order,
                        'status' => true,
                        'updated_at' => now(),
                    ],
                );

                $key = $this->key($sedeName, $departmentName, $positionName);
                $positionIds[$key] = (int) DB::table('positions')
                    ->where('department_id', $departmentId)->where('name', $positionName)->value('id');
            }

            // Segunda pasada: resuelve el mapa explícito sin IDs fijos de departments/positions.
            foreach ($rows as [$sedeName, $departmentName, $positionName]) {
                $key = $this->key($sedeName, $departmentName, $positionName);
                $supervisorKey = $supervisors[$key] ?? null;
                $supervisorId = $supervisorKey === null ? null : ($positionIds[$supervisorKey] ?? null);

                if ($supervisorId === $positionIds[$key]) {
                    $supervisorId = null;
                }

                DB::table('positions')->where('id', $positionIds[$key])->update([
                    'supervisor_id' => $supervisorId,
                    'updated_at' => now(),
                ]);
            }
        });
    }

    /** @return array<string, int> */
    private function resolveSedeIds(): array
    {
        $ids = [];

        foreach (self::SEDES as $name) {
            $matches = DB::table('sedes')
                ->whereRaw('UPPER(TRIM(name)) = ?', [mb_strtoupper($name, 'UTF-8')])
                ->select('id')
                ->limit(2)
                ->get();

            if ($matches->isEmpty()) {
                throw new RuntimeException("No existe la sede requerida '{$name}'. Ejecuta primero SedeSeeder.");
            }

            if ($matches->count() > 1) {
                throw new RuntimeException("La sede '{$name}' está duplicada y no puede resolverse de forma inequívoca.");
            }

            $ids[$name] = (int) $matches->first()->id;
        }

        return $ids;
    }

