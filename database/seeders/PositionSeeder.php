    private function hierarchyOrder(string $name): int
    {
        $upper = mb_strtoupper($name);
        return match (true) {
            str_contains($upper, 'CONSEJERO') => 5,
            str_contains($upper, 'DIRECTOR') || str_contains($upper, 'DIRECTORA') => 10,
            str_contains($upper, 'GERENTE') => 20,
            str_contains($upper, 'COORDINADOR') || str_contains($upper, 'COORD ') => 30,
            str_contains($upper, 'SUBCOORD') => 35,
            str_contains($upper, 'SUPERVISOR') || str_contains($upper, 'JEFE') => 40,
            str_contains($upper, 'TECNICO LIDER') => 50,
            str_contains($upper, 'ASISTENTE') || str_contains($upper, 'ANALISTA') || str_contains($upper, 'AUDITOR') || str_contains($upper, 'MEDICO') || str_contains($upper, 'INSTRUCTOR') => 60,
            str_contains($upper, 'AUXILIAR') || str_contains($upper, 'AUX ') => 70,
            default => 80,
        };
    }

